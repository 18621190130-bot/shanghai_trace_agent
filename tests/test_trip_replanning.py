import json
import unittest
from unittest.mock import patch

from tools.demos.trip_demo import load_fixture
from src.intent_adapter import intent_to_route_request
from src.intent_models import RouteIntent
from src.poi_repository import POIRepository
from src.route_engine import RouteEngine
from src.trip_replanning import (ContinuationRouteEngine, InTripPolicy, ReplanningCoordinator,
                                 ReplanReason, logical_origin)
from src.trip_state import TripState, TripStateDelta, TripStateError
from src.trip_store import InMemoryTripStore, StaleStateConflict, TripService

AT = '2026-10-05T10:00:00+08:00'


class ReplanningTests(unittest.TestCase):
    def setUp(self):
        self.repo = POIRepository()
        self.store = InMemoryTripStore(clock=lambda: AT)
        self.service = TripService(self.store, clock=lambda: AT)
        self.plan, self.intent = load_fixture()
        self.trip = self.service.create_trip(self.plan, self.intent)
        self.tid = self.trip.trip_id
        self.service.start_trip(self.tid)
        self.coordinator = ReplanningCoordinator(self.store, self.repo)

    def progress(self):
        self.service.complete_stop(self.tid, 'p29')
        self.service.update_elapsed_time(self.tid, 60)

    def replan(self, **kwargs):
        return self.coordinator.replan(self.tid, TripStateDelta(request_replan=True, **kwargs))

    def state(self):
        return self.store.get(self.tid)

    def assert_success(self, result):
        self.assertIn(result.status, ('success', 'success_shortened'), result.diagnostics.get('error', result.status))
        self.assertTrue(result.committed)

    def failing_factory(self, hook):
        def factory(repo, context):
            engine = ContinuationRouteEngine(repo, context)
            original = engine.generate_route
            def generate(request):
                plan = original(request)
                return hook(plan)
            engine.generate_route = generate
            return engine
        return factory

    def unchanged_failure(self, expected, **kwargs):
        before = self.state().to_dict()
        result = self.replan(**kwargs)
        self.assertEqual(result.status, expected, result.diagnostics.get('error', result.status))
        self.assertFalse(result.committed)
        self.assertEqual(self.state().to_dict(), before)
        return result

    def test_excluded_visited_skipped_and_explicit_skip_survives_failure(self):
        self.progress();self.service.skip_stop(self.tid, 'p30')
        self.unchanged_failure('insufficient_remaining_route', remaining_minutes=0)
        result = self.replan(add_must_go_poi_ids=['p36'])
        self.assert_success(result)
        self.assertFalse({'p29', 'p30'} & set(self.state().remaining_poi_ids))
        self.assertEqual(set(self.state().get_replan_excluded_poi_ids()), {'p29', 'p30'})

    def test_originals_and_v1_permanent_new_route_active(self):
        before = self.state();self.progress()
        result = self.replan(remaining_minutes=60);self.assert_success(result)
        after = self.state()
        self.assertEqual(before.original_route, after.original_route)
        self.assertEqual(before.original_intent, after.original_intent)
        self.assertEqual(before.route_versions[0], after.route_versions[0])
        self.assertEqual(after.active_route, result.proposed_route)
        self.assertEqual(after.route_versions[-1]['version_id'], 'v2')
        self.assertNotIn('p29', after.remaining_poi_ids)

    def test_second_replan_version_parent_chain(self):
        self.progress();self.assert_success(self.replan(remaining_minutes=100))
        self.assert_success(self.replan(remaining_minutes=80))
        versions = self.state().route_versions
        self.assertEqual([v['version_id'] for v in versions], ['v1', 'v2', 'v3'])
        self.assertEqual([v['parent_version_id'] for v in versions], [None, 'v1', 'v2'])

    def test_failure_staged_preferences_must_and_budget_rollback(self):
        self.progress()
        self.unchanged_failure('infeasible_must_go', remaining_minutes=1,
                               add_interest_tags=['architecture'], add_must_go_poi_ids=['p36'])

    def test_visited_anchor_two_future_stops_without_anchor(self):
        # Both initial and continuation sequences are generated by the real engine.
        intent = RouteIntent(route_mode='places_in_mind', available_minutes=180,
                             preferred_zone='west_bund', must_go_poi_ids=['p29', 'p38', 'p42'])
        plan = RouteEngine(self.repo).generate_route(intent_to_route_request(intent))
        trip = self.service.create_trip(plan, intent);self.tid = trip.trip_id
        self.service.start_trip(self.tid);self.service.complete_stop(self.tid, 'p29')
        result = self.replan(remaining_minutes=100)
        self.assert_success(result)
        self.assertEqual(len(result.proposed_route['ordered_pois']), 2)
        self.assertNotIn('anchor', [s['effective_primary_role'] for s in result.proposed_route['ordered_pois']])
        self.assertTrue(result.diagnostics['in_trip_policy']['composition_passed'])

    def test_policy_two_visited_one_remaining(self):
        context = dict(visited_stop_count=2, visited_roles=['anchor', 'supporting_stop'])
        self.assertTrue(InTripPolicy.assess(context, ['transition_stop'])['minimum_passed'])
        self.assertTrue(InTripPolicy.assess(context, ['transition_stop'])['composition_passed'])

    def test_policy_three_visited_one_or_two_remaining(self):
        context = dict(visited_stop_count=3, visited_roles=['anchor', 'supporting_stop', 'transition_stop'])
        for roles in [['transition_stop'], ['supporting_stop', 'transition_stop']]:
            self.assertTrue(InTripPolicy.assess(context, roles)['minimum_passed'])

    def test_no_visited_keeps_initial_minimum_and_engine_composition(self):
        self.unchanged_failure('insufficient_remaining_route', remaining_minutes=60)
        context = self.state().get_journey_context()
        request = intent_to_route_request(self.intent)
        self.assertEqual(RouteEngine(self.repo).generate_route(request).to_dict(),
                         ContinuationRouteEngine(self.repo, context).generate_route(request).to_dict())

    def test_time_reduction_and_shortened_no_filler(self):
        self.progress();result = self.replan(remaining_minutes=60)
        self.assertEqual(result.status, 'success_shortened')
        self.assertEqual(result.effective_remaining_minutes, 60)
        self.assertLessEqual(result.proposed_route['total_estimated_minutes'], 60)
        self.assertLess(len(result.proposed_route['ordered_pois']), len(self.plan.ordered_pois)-1)
        self.assertEqual(self.state().remaining_minutes, 60)

    def test_larger_override_never_replenishes_time_and_deadline_persists(self):
        self.progress();self.assert_success(self.replan(remaining_minutes=80))
        self.service.update_elapsed_time(self.tid, 70)
        result = self.replan(remaining_minutes=120)
        self.assertEqual(result.effective_remaining_minutes, 70)
        self.assertEqual(self.state().remaining_minutes, 70)
        self.service.update_elapsed_time(self.tid, 75)
        self.assertEqual(self.state().remaining_minutes, 65)

    def test_avoid_museums_affects_future_and_not_visited_museum(self):
        self.progress();result = self.replan(add_avoid_tags=['museum_visit'])
        self.assert_success(result)
        self.assertIn('museum_visit', self.repo.get_poi_by_id('p29').experience_tags)
        self.assertEqual(self.state().visited_poi_ids, ['p29'])
        for pid in self.state().remaining_poi_ids:
            self.assertNotIn('museum_visit', self.repo.get_poi_by_id(pid).experience_tags)
        self.assertIn('museum_visit', self.state().current_intent['avoid_tags'])

    def test_interest_commit_and_matched_interest_original_frozen(self):
        self.progress();before = self.state().original_intent
        result = self.replan(add_interest_tags=['architecture']);self.assert_success(result)
        self.assertEqual(self.state().original_intent, before)
        self.assertIn('architecture', self.state().current_intent['interest_tags'])
        self.assertTrue(any('architecture' in s['matched_tags'].get('interest_tags', [])
                            for s in result.proposed_route['ordered_pois']))

    def test_feasible_must_go_included(self):
        self.progress();result = self.replan(add_must_go_poi_ids=['p36'])
        self.assert_success(result)
        self.assertIn('p36', self.state().remaining_poi_ids)
        self.assertIn('p36', self.state().must_go_remaining)

    def test_cross_zone_must_go_explicit_failure(self):
        pid = next(p.id for p in self.repo.get_all_pois() if p.zone_id != 'west_bund')
        self.progress();self.unchanged_failure('infeasible_must_go', add_must_go_poi_ids=[pid])

    def test_must_go_skip_conflict_no_restore(self):
        self.progress();self.service.skip_stop(self.tid, 'p30')
        self.unchanged_failure('must_go_conflict', add_must_go_poi_ids=['p30'])
        self.assertEqual(self.state().skipped_poi_ids, ['p30'])

    def test_visited_must_go_already_satisfied(self):
        self.progress();result = self.replan(remaining_minutes=100, add_must_go_poi_ids=['p29'])
        self.assert_success(result)
        self.assertEqual(result.diagnostics['already_satisfied_must_go'], ['p29'])
        self.assertNotIn('p29', self.state().remaining_poi_ids)

    def test_unknown_must_go_and_taxonomy_invalid(self):
        self.progress()
        self.unchanged_failure('invalid_delta', add_must_go_poi_ids=['nonexistent'])
        self.unchanged_failure('invalid_delta', add_interest_tags=['invented_tag'])

    def test_must_go_avoid_conflict(self):
        self.progress();self.unchanged_failure('infeasible_must_go', add_must_go_poi_ids=['p5'],
                                             add_avoid_tags=['museum_visit'])

    def test_cas_stale_proposal_cannot_overwrite_saved_progress(self):
        self.progress()
        def raced(plan):
            self.service.skip_stop(self.tid, 'p30')
            return plan
        self.coordinator.engine_factory = self.failing_factory(raced)
        result = self.replan(remaining_minutes=60)
        self.assertEqual(result.status, 'stale_state_conflict')
        self.assertFalse(result.committed)
        self.assertEqual(self.state().skipped_poi_ids, ['p30'])
        self.assertEqual(len(self.state().route_versions), 1)
        self.assertEqual(self.state().remaining_minutes, 120)

    def test_engine_exception_preserves_all_state(self):
        self.progress()
        def fail(plan):raise RuntimeError('injected engine exception')
        self.coordinator.engine_factory = self.failing_factory(fail)
        self.unchanged_failure('engine_failure', add_interest_tags=['architecture'])

    def test_invalid_engine_output_rejected_without_commit(self):
        self.progress()
        self.coordinator.engine_factory = self.failing_factory(lambda plan: None)
        self.unchanged_failure('engine_failure', remaining_minutes=60)

    def test_engine_cannot_reintroduce_visited_identity_or_change_role(self):
        self.progress()
        for mutation in [lambda s: setattr(s, 'poi_id', 'p29'),
                         lambda s: setattr(s, 'effective_primary_role', 'supporting_stop')]:
            def hook(plan):mutation(plan.ordered_pois[0]);return plan
            self.coordinator.engine_factory = self.failing_factory(hook)
            self.unchanged_failure('engine_failure', remaining_minutes=60)

    def test_v2_v3_serialization_roundtrip_and_tamper_rejected(self):
        self.progress();self.assert_success(self.replan(remaining_minutes=100))
        self.assert_success(self.replan(remaining_minutes=80))
        raw = json.loads(json.dumps(self.state().to_dict()))
        self.assertEqual(TripState.from_dict(raw).to_dict(), raw)
        raw['route_versions'][1]['parent_version_id'] = 'fake'
        with self.assertRaises(TripStateError):TripState.from_dict(raw)

    def test_replan_record_and_append_only_event(self):
        self.progress();before = self.state()
        result = self.coordinator.replan(self.tid, TripStateDelta(remaining_minutes=60, request_replan=True),
                                         primary_reason=ReplanReason.TIME_REDUCED)
        self.assert_success(result);after = self.state();record = after.replan_history[0]
        self.assertEqual(record['old_route_version_id'], 'v1')
        self.assertEqual(record['new_route_version_id'], 'v2')
        self.assertEqual(record['reason'], 'time_reduced')
        self.assertEqual(record['visited_at_replan'], ['p29'])
        self.assertEqual(record['effective_remaining_minutes'], 60)
        self.assertEqual(record['delta']['remaining_minutes'], 60)
        self.assertTrue(record['replan_id']);self.assertTrue(record['timestamp'])
        self.assertEqual(after.event_history[:-1], before.event_history)
        self.assertEqual(after.event_history[-1]['event_type'], 'route_replanned')
        self.assertEqual(after.state_revision, before.state_revision+1)

    def test_manual_equivalent_no_change_no_fake_version(self):
        self.progress();self.assert_success(self.replan(remaining_minutes=100))
        before = self.state().to_dict();result = self.replan()
        self.assertEqual(result.status, 'no_change')
        self.assertFalse(result.committed);self.assertEqual(self.state().to_dict(), before)

    def test_manual_initial_equivalent_does_not_reorder_tags(self):
        lat, lng = self.repo.get_poi_by_id('p29').coordinates
        intent = RouteIntent(route_mode='places_in_mind', available_minutes=180,
                             start_lat=lat, start_lng=lng, preferred_zone='west_bund',
                             interest_tags=['waterfront', 'industrial_heritage'],
                             must_go_poi_ids=['p29', 'p38', 'p42'])
        plan = RouteEngine(self.repo).generate_route(intent_to_route_request(intent))
        trip = self.service.create_trip(plan, intent);self.tid = trip.trip_id
        self.service.start_trip(self.tid)
        before = self.state().to_dict()
        result = self.replan()
        self.assertEqual(result.status, 'no_change', result.diagnostics.get('error'))
        self.assertEqual(before, self.state().to_dict())

    def test_non_selectable_must_go_not_admitted(self):
        self.progress();raw = self.repo.get_raw_data()
        next(p for p in raw['pois'] if p['id'] == 'p36')['route_selectable'] = False
        with patch.object(self.repo, 'get_raw_data', return_value=raw):
            self.unchanged_failure('infeasible_must_go', add_must_go_poi_ids=['p36'])

    def test_all_visited_or_skipped_never_fabricates_continuation(self):
        for pid in list(self.state().remaining_poi_ids):self.service.skip_stop(self.tid, pid)
        self.unchanged_failure('insufficient_remaining_route')
        other = self.service.create_trip(self.plan, self.intent);self.tid = other.trip_id
        self.service.start_trip(self.tid)
        for pid in list(self.state().remaining_poi_ids):self.service.complete_stop(self.tid, pid)
        self.unchanged_failure('invalid_state')

    def test_legacy_3a1_snapshot_upgrades_revision_and_v1(self):
        raw = self.state().to_dict();raw.pop('state_revision')
        raw['route_versions'][0].pop('parent_version_id')
        raw['route_versions'][0].pop('effective_remaining_minutes')
        restored = TripState.from_dict(raw)
        self.assertEqual(restored.state_revision, 2)
        self.assertIsNone(restored.route_versions[0]['parent_version_id'])

    def test_logical_origin_route_order_not_completion_event_order(self):
        self.service.complete_stop(self.tid, 'p30');self.service.complete_stop(self.tid, 'p29')
        origin = logical_origin(self.state(), self.repo)
        self.assertEqual(origin['poi_id'], 'p30')
        self.assertIn('not GPS', origin['basis'])

    def test_newly_discovered_stop_completion_keeps_old_visited_roles(self):
        self.progress();self.assert_success(self.replan(add_must_go_poi_ids=['p36']))
        self.service.complete_stop(self.tid, 'p36')
        self.assertEqual(self.state().get_journey_context()['visited_stop_count'], 2)
        self.assertIn('supporting_stop', self.state().get_journey_context()['visited_roles'])
        self.assertIn('p29', self.state().get_replan_excluded_poi_ids())

    def test_staged_skip_requires_saved_core_operation(self):
        self.unchanged_failure('invalid_delta', skip_poi_ids=['p30'])

    def test_composition_gap_all_anchors_avoided_never_role_upgrade(self):
        # A transition already visited cannot supply the missing theme anchor.
        self.service.complete_stop(self.tid, 'p42')
        self.unchanged_failure('composition_gap', add_avoid_tags=['museum_visit', 'shopping_leisure'])

    def test_revision_mismatch_and_history_rewrite_rejected(self):
        local = self.state();revision = local.state_revision
        self.service.update_elapsed_time(self.tid, 10)
        with self.assertRaises(StaleStateConflict):self.store.save_if_revision(local, revision)
        raw = self.state().to_dict();raw['state_revision'] += 1
        with self.assertRaises(TripStateError):TripState.from_dict(raw)


